function russianField(label: string): string {
  if (fieldNames[label]) return fieldNames[label];
  const line = /^Line (\d+)$/.exec(label);
  if (line) return `Позиция ${line[1]}`;
  const scope = /^(Included scope|Excluded scope) (\d+)$/.exec(label);
  if (scope) return `${fieldNames[scope[1]]}, пункт ${scope[2]}`;
  return 'Поле';
}

/** Known English validation errors remain stable for v1 data and are translated at the UI boundary. */
export function domainErrorRu(message: string): string | undefined {
  if (domainRu[message]) return domainRu[message];
  let match = /^(.*?) must be an object\.$/.exec(message);
  if (match) return `${russianField(match[1])}: ожидается объект.`;
  match = /^(.*?) must be text of at most (\d+) characters\.$/.exec(message);
  if (match) return `${russianField(match[1])}: введите текст длиной не более ${match[2]} символов.`;
  match = /^(.*?) is not a valid identifier\.$/.exec(message);
  if (match) return `${russianField(match[1])}: некорректный идентификатор.`;
  match = /^(.*?) must be (a whole number|a number) between ([\d.]+) and ([\d.]+)\.$/.exec(message);
  if (match) return `${russianField(match[1])}: введите ${match[2] === 'a whole number' ? 'целое число' : 'число'} от ${match[3]} до ${match[4]}.`;
  match = /^(.*?) must be a valid ISO date\.$/.exec(message);
  if (match) return `${russianField(match[1])}: укажите корректную дату в формате ISO.`;
  match = /^(.*?) must be a list of at most 100 entries\.$/.exec(message);
  if (match) return `${russianField(match[1])}: список должен содержать не более 100 пунктов.`;
  match = /^A backup can contain at most (\d+) proposals\.$/.exec(message);
  if (match) return `Резервная копия может содержать не более ${match[1]} предложений.`;
  match = /^Backup must contain a list of at most (\d+) proposals\.$/.exec(message);
  if (match) return `Резервная копия должна содержать список не более чем из ${match[1]} предложений.`;
  return undefined;
}
